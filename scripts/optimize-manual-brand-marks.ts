function sanitizeSvg(raw: string): string | null {
  if (!raw.includes("<svg") || raw.includes("<!DOCTYPE html") || raw.includes("File not found")) return null;
  // Strip scripts / foreignObject / external refs
  let s = raw
    .replace(/<\?xml[^>]*>/gi, "")
    .replace(/<!DOCTYPE[^>]*>/gi, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<script[\s\S]*?<\/script>/gi, "")
    .replace(/<foreignObject[\s\S]*?<\/foreignObject>/gi, "")
    .replace(/\s(?:onload|onclick|onerror)=["'][^"']*["']/gi, "")
    .replace(/xlink:href=["']https?:\/\/[^"']*["']/gi, "")
    .trim();
  // Ensure xmlns
  if (!/xmlns=/.test(s)) {
    s = s.replace("<svg", '<svg xmlns="http://www.w3.org/2000/svg"');
  }
  // Cap size for performance — reject huge assets
  if (s.length > 80_000) return null;
  return s;
}

fs.mkdirSync(OUT_DIR, { recursive: true });
const marks: Record<string, { title: string; hex: string; file: string }> = {};

const files = fs.existsSync(SRC_DIR)
  ? fs.readdirSync(SRC_DIR).filter((f) => f.endsWith(".svg"))
  : [];

for (const file of files) {
  const slug = file.replace(/\.svg$/i, "").toLowerCase();
  const raw = fs.readFileSync(path.join(SRC_DIR, file), "utf8");
  const svg = sanitizeSvg(raw);
  if (!svg) {
    console.warn(`skip invalid: ${file}`);
    continue;
  }
  const outName = `${slug}.svg`;
  fs.writeFileSync(path.join(OUT_DIR, outName), svg, "utf8");
  marks[slug] = {
    title: TITLES[slug] ?? slug,
    hex: HEX[slug] ?? "1A7F4E",
    file: `/brand-marks/${outName}`,
  };
  console.log(`wrote ${outName} (${svg.length} bytes)`);
}

